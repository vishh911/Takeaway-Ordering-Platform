package com.campuseateries.model;

import java.math.BigDecimal;

/** Menu entity linking restaurant FK + category FK to satisfy relational modeling + OOP cohesion. */
public class MenuItem {

    private long menuItemId;
    private long restaurantId;

    private int categoryId;
    private String categoryName;
    private String itemName;
    private String description;
    private BigDecimal unitPrice;
    private int stockQuantity;
    private boolean available;
    private String restaurantNameSnapshot;

    public MenuItem() {
    }

    public long getMenuItemId() {
        return menuItemId;
    }

    public void setMenuItemId(long menuItemId) {
        this.menuItemId = menuItemId;
    }

    public long getRestaurantId() {
        return restaurantId;
    }

    public void setRestaurantId(long restaurantId) {
        this.restaurantId = restaurantId;
    }

    public String getRestaurantNameSnapshot() {
        return restaurantNameSnapshot;
    }

    public void setRestaurantNameSnapshot(String restaurantNameSnapshot) {
        this.restaurantNameSnapshot = restaurantNameSnapshot;
    }

    public int getCategoryId() {
        return categoryId;
    }

    public void setCategoryId(int categoryId) {
        this.categoryId = categoryId;
    }

    public String getCategoryName() {
        return categoryName;
    }

    public void setCategoryName(String categoryName) {
        this.categoryName = categoryName;
    }

    public String getItemName() {
        return itemName;
    }

    public void setItemName(String itemName) {
        this.itemName = itemName;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public BigDecimal getUnitPrice() {
        return unitPrice;
    }

    public void setUnitPrice(BigDecimal unitPrice) {
        this.unitPrice = unitPrice;
    }

    public int getStockQuantity() {
        return stockQuantity;
    }

    public void setStockQuantity(int stockQuantity) {
        this.stockQuantity = stockQuantity;
    }

    public boolean isAvailable() {
        return available;
    }

    public void setAvailable(boolean available) {
        this.available = available;
    }
}
